// BidResult model (bidResults)
import mongoose from 'mongoose';
import { TERM_KEY, ROUNDS, catalogueOptions } from '../shared.js';

const { Schema } = mongoose;

const bidResultSchema = new Schema({     // _id generated by MongoDB
  moduleCode: { type: String, ref: 'Module', required: true },
  termKey: { type: String, match: TERM_KEY, required: true },
  session: String,
  round: { type: String, enum: ROUNDS, required: true },
  window: { type: Number, required: true },
  sectionCode: String,
  instructor: String,
  sectionsOfferedInTerm: Number,
  vacancy: Number,
  openingVacancy: Number,
  beforeProcessVacancy: Number,
  dice: Number,
  afterProcessVacancy: Number,
  enrolled: Number,
  medianBid: Number,
  minBid: Number,
}, catalogueOptions);

bidResultSchema.index({ moduleCode: 1, instructor: 1, termKey: 1 });
bidResultSchema.index({ moduleCode: 1, termKey: 1, round: 1, window: 1 });

export default mongoose.model('BidResult', bidResultSchema, 'bidResults');
