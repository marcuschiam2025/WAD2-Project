// TrainingResponse model (trainingResponses). Only needed if the recommender uses kNN.
import mongoose from 'mongoose';
import { TRACK_CODES, answerSchema, catalogueOptions } from '../shared.js';

const { Schema } = mongoose;

const trainingResponseSchema = new Schema({   // _id generated by MongoDB
  source: { type: String, enum: ['survey', 'mock'], required: true },
  answers: [answerSchema],
  declaredTrack: { type: String, enum: TRACK_CODES, required: true },
  collectedAt: Date,
}, catalogueOptions);

export default mongoose.model('TrainingResponse', trainingResponseSchema, 'trainingResponses');
